package fuzz

import (
	"testing"

	"github.com/gdns/internal/dns/parser"
)

func FuzzDnsParse(f *testing.F) {
	f.Add([]byte{
		0x00, 0x01, // ID
		0x01, 0x00, // flags: RD=1
		0x00, 0x01, // QDCOUNT
		0x00, 0x00, // ANCOUNT
		0x00, 0x00, // NSCOUNT
		0x00, 0x00, // ARCOUNT
		0x01, 'a', // "a"
		0x01, 'b', // "b"
		0x00,       // null terminator
		0x00, 0x01, // QTYPE A
		0x00, 0x01, // QCLASS IN
	})
	f.Fuzz(func(t *testing.T, b []byte) {
		d := parser.CreateNewDnsStruct()
		_ = d.Parse(b)
	})
}

func FuzzParseAnswer(f *testing.F) {
	// Seed 1: Minimal A record answer with pointer NAME
	f.Add([]byte{
		0x00, 0x01, 0x81, 0x80, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00,
		0x01, 'a', 0x00, 0x00, 0x01, 0x00, 0x01,
		0xC0, 0x0C, // NAME pointer to offset 12
		0x00, 0x01, // TYPE A
		0x00, 0x01, // CLASS IN
		0x00, 0x00, 0x01, 0x2C, // TTL = 300
		0x00, 0x04, // RDLENGTH
		0x08, 0x08, 0x08, 0x08, // 8.8.8.8
	})

	// Seed 2: Answer with literal NAME (no pointer)
	f.Add([]byte{
		0x00, 0x01, 0x81, 0x80, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00,
		0x01, 'x', 0x00, 0x00, 0x01, 0x00, 0x01,
		0x01, 'y', 0x00, // NAME "y" (literal, not pointer)
		0x00, 0x01, // TYPE A
		0x00, 0x01, // CLASS IN
		0x00, 0x00, 0x00, 0x3C, // TTL = 60
		0x00, 0x04, // RDLENGTH
		0x01, 0x02, 0x03, 0x04, // 1.2.3.4
	})

	// Seed 3: Answer with labels-then-pointer NAME (compression)
	f.Add([]byte{
		0x00, 0x01, 0x81, 0x80, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00,
		0x03, 'f', 'o', 'o', 0x03, 'b', 'a', 'r', 0x00,
		0x00, 0x01, 0x00, 0x01,
		0x03, 'b', 'a', 'z', // "baz"
		0xC0, 0x10, // pointer to offset 16 (start of "bar")
		0x00, 0x01, // TYPE A
		0x00, 0x01, // CLASS IN
		0x00, 0x00, 0x00, 0x3C, // TTL
		0x00, 0x04, // RDLENGTH
		0x7F, 0x00, 0x00, 0x01, // 127.0.0.1
	})

	// Seed 4: Truncated/malformed — short answer section
	f.Add([]byte{
		0x00, 0x01, 0x81, 0x80, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00,
		0x01, 'a', 0x00, 0x00, 0x01, 0x00, 0x01,
		0xC0, 0x0C,
	})

	f.Fuzz(func(t *testing.T, b []byte) {
		if len(b) < 12 {
			return
		}
		q := parser.CreateQuestion()
		if err := q.ParseQuestion(b[12:]); err != nil {
			return
		}
		a := parser.NewAnswer()
		_ = a.ParseAnswer(b, q.Len) // must not panic
	})
}
